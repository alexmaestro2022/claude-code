"""
AILA - Trading Signals Module

Defines trading signal models and types used by strategies.
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional


class SignalType(Enum):
    """Trading signal types."""

    LONG = "long"
    SHORT = "short"
    CLOSE_LONG = "close_long"
    CLOSE_SHORT = "close_short"
    NO_SIGNAL = "no_signal"


class SignalStrength(Enum):
    """Signal strength levels."""

    WEAK = "weak"
    NORMAL = "normal"
    STRONG = "strong"


@dataclass
class Signal:
    """
    Trading signal generated by a strategy.

    Attributes:
        signal_type: Type of signal (LONG, SHORT, etc.)
        symbol: Trading pair symbol
        price: Current price at signal generation
        timestamp: Time of signal generation
        strength: Signal strength
        stop_loss: Suggested stop-loss price
        take_profit: Suggested take-profit price
        position_size_multiplier: Multiplier for position size (0-1)
        metadata: Additional signal metadata
    """

    signal_type: SignalType
    symbol: str
    price: float
    timestamp: datetime = field(default_factory=datetime.utcnow)
    strength: SignalStrength = SignalStrength.NORMAL
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    position_size_multiplier: float = 1.0
    metadata: dict = field(default_factory=dict)

    @property
    def is_entry(self) -> bool:
        """Check if signal is an entry signal."""
        return self.signal_type in (SignalType.LONG, SignalType.SHORT)

    @property
    def is_exit(self) -> bool:
        """Check if signal is an exit signal."""
        return self.signal_type in (SignalType.CLOSE_LONG, SignalType.CLOSE_SHORT)

    @property
    def is_long(self) -> bool:
        """Check if signal is a long signal."""
        return self.signal_type == SignalType.LONG

    @property
    def is_short(self) -> bool:
        """Check if signal is a short signal."""
        return self.signal_type == SignalType.SHORT

    @property
    def direction(self) -> int:
        """Get signal direction as integer (1 for long, -1 for short, 0 for no signal)."""
        if self.signal_type == SignalType.LONG:
            return 1
        elif self.signal_type == SignalType.SHORT:
            return -1
        return 0

    def to_dict(self) -> dict:
        """Convert signal to dictionary."""
        return {
            "signal_type": self.signal_type.value,
            "symbol": self.symbol,
            "price": self.price,
            "timestamp": self.timestamp.isoformat(),
            "strength": self.strength.value,
            "stop_loss": self.stop_loss,
            "take_profit": self.take_profit,
            "position_size_multiplier": self.position_size_multiplier,
            "metadata": self.metadata,
        }

    @classmethod
    def no_signal(cls, symbol: str, price: float) -> "Signal":
        """Create a no-signal instance."""
        return cls(
            signal_type=SignalType.NO_SIGNAL,
            symbol=symbol,
            price=price,
        )

    @classmethod
    def long(
        cls,
        symbol: str,
        price: float,
        stop_loss: Optional[float] = None,
        take_profit: Optional[float] = None,
        **kwargs,
    ) -> "Signal":
        """Create a long signal."""
        return cls(
            signal_type=SignalType.LONG,
            symbol=symbol,
            price=price,
            stop_loss=stop_loss,
            take_profit=take_profit,
            **kwargs,
        )

    @classmethod
    def short(
        cls,
        symbol: str,
        price: float,
        stop_loss: Optional[float] = None,
        take_profit: Optional[float] = None,
        **kwargs,
    ) -> "Signal":
        """Create a short signal."""
        return cls(
            signal_type=SignalType.SHORT,
            symbol=symbol,
            price=price,
            stop_loss=stop_loss,
            take_profit=take_profit,
            **kwargs,
        )

    def __repr__(self) -> str:
        return (
            f"Signal({self.signal_type.value}, {self.symbol}, "
            f"price={self.price}, sl={self.stop_loss}, tp={self.take_profit})"
        )
